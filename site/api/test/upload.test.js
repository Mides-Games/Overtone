import assert from 'node:assert/strict';
import { test } from 'node:test';

import { audioExtension, cleanFilename, downloadName, timingCsv, timingText } from '../src/utils/upload.js';

test('a filename keeps its last segment and loses path and control characters', () => {
  assert.equal(cleanFilename('song.mp3'), 'song.mp3');
  assert.equal(cleanFilename(encodeURIComponent('Canción — final.flac')), 'Canción — final.flac');
  assert.equal(cleanFilename('..%2F..%2Fetc%2Fpasswd.wav'), 'passwd.wav');
  assert.equal(cleanFilename('C:\\Users\\me\\a.wav'), 'a.wav');
  assert.equal(cleanFilename('a\u0000b<>:"|?*.ogg'), 'ab.ogg');
  assert.equal(cleanFilename('...hidden.wav'), 'hidden.wav');
  assert.equal(cleanFilename('%E0%A4%A'), '%E0%A4%A');
  assert.equal(cleanFilename(''), null);
  assert.equal(cleanFilename('../..'), null);
  assert.equal(cleanFilename(undefined), null);
});

test('a long filename is cut to 200 characters with its extension kept', () => {
  const name = cleanFilename(`${'x'.repeat(300)}.opus`);
  assert.equal(name.length, 200);
  assert.ok(name.endsWith('.opus'));
});

test('only the formats the engine reads pass', () => {
  for (const ext of ['mp3', 'OGG', 'wav', 'flac', 'm4a', 'opus']) assert.equal(audioExtension(`a.${ext}`), ext.toLowerCase());
  for (const name of ['a.exe', 'a.wav.exe', 'wav', 'a.', null]) assert.equal(audioExtension(name), null);
});

test('download names are ASCII and end in the suffix', () => {
  assert.equal(downloadName('Canción "x".mp3', 'timing.txt'), 'Cancin x-timing.txt');
  assert.equal(downloadName('ñ.mp3', 'timing.csv'), 'overtone-timing.csv');
});

const result = {
  red_lines: [
    { time_ms: 400.127, bpm: 128, beat_length_ms: 468.75, meter: 4 },
    { time_ms: 30400.127, bpm: 142, beat_length_ms: 422.535211, meter: 4 },
  ],
  sections: [
    { confidence: 0.997, level: 'high' },
    { confidence: 0.6, level: 'check' },
  ],
  osu_timing: '// Generated by Overtone\n400,468.75,4,1,0,100,1,0\n30400,422.535211,4,1,0,100,1,0',
};

test('the [TimingPoints] block is the engine text with CRLF', () => {
  assert.equal(
    timingText(result),
    '[TimingPoints]\r\n// Generated by Overtone\r\n400,468.75,4,1,0,100,1,0\r\n30400,422.535211,4,1,0,100,1,0\r\n',
  );
});

test('the CSV has one row per red line', () => {
  assert.equal(
    timingCsv(result),
    'time_ms,bpm,beat_length_ms,meter,confidence,level\r\n400.127,128,468.75,4,0.997,high\r\n30400.127,142,422.535211,4,0.6,check\r\n',
  );
});
