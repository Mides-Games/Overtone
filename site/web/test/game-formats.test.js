/**
 * Fixture red lines: 150 BPM 4/4 from 1234.567 ms; a change to 140 BPM in
 * 3/4 151.3 ms past beat 75 of the first line (beat 75.37825, off the grid);
 * back to 4/4 at the same tempo 60 beats later (a meter change alone).
 */
const B2 = 1234.567 + 75 * 400 + 151.3
const B3 = B2 + (60 * 60000) / 140
const lines = [
  { timeMs: 1234.567, beatMs: 60000 / 150, meter: 4 },
  { timeMs: B2, beatMs: 60000 / 140, meter: 3 },
  { timeMs: B3, beatMs: 60000 / 140, meter: 4 },
]

test("fixed() rounds as Python's format does: exact ties to even, no -0", () => {
  assert.equal(fixed(0.125, 2), '0.12')
  assert.equal(fixed(0.375, 2), '0.38')
  assert.equal(fixed(2.5, 0), '2')
  assert.equal(fixed(3.5, 0), '4')
  assert.equal(fixed(1.005, 2), '1.00') // 1.005 is a hair under, as a double
  assert.equal(fixed(-0.0000001, 6), '0.000000')
  assert.equal(fixed(-0, 3), '0.000')
  assert.equal(fixed(-1.5, 0), '-2')
})

test('Quaver: absolute StartTime and Bpm per line, Triple on a 3/4 line, nothing accumulated', () => {
  assert.equal(
    quaverTimingText(lines, { offsetDecimals: 3 }),
    [
      '# Generated by the Overtone site: timing only, no notes',
      'TimingPoints:',
      '- StartTime: 1234.567',
      '  Bpm: 150',
      '- StartTime: 31385.867',
      '  Bpm: 140',
      '  Signature: Triple',
      '- StartTime: 57100.153',
      '  Bpm: 140',
      '',
    ].join('\n'),
  )
  // Whole ms at 0 decimals, half to even as v3's round().
  const whole = quaverTimingText([{ timeMs: 2.5, beatMs: 600, meter: 4 }, { timeMs: 603.5, beatMs: 60000 / 123.4567891, meter: 4 }])
  assert.match(whole, /StartTime: 2\n {2}Bpm: 100\n- StartTime: 604\n {2}Bpm: 123.456789\n$/)
})

test('a whole .qua: YAML with the metadata quoted, the points, no notes', () => {
  const { name, text, report } = gameFile('qua', { analysis: { filename: "Band - It's.ogg" }, lines, offsetDecimals: 1 })
  assert.equal(name, "Band - Its.qua")
  assert.match(text, /^AudioFile: 'Band - It''s.ogg'$/m)
  assert.match(text, /^Title: 'It''s'$/m)
  assert.match(text, /^Mode: Keys4$/m)
  assert.match(text, /^- StartTime: 31385.9$/m)
  assert.match(text, /^HitObjects: \[\]$/m)
  assert.equal(report.meterLost, 0)
  const seven = gameFile('qua', { analysis: {}, lines: [{ timeMs: 0, beatMs: 500, meter: 7 }] })
  assert.equal(seven.report.meterLost, 1)
  assert.doesNotMatch(seven.text, /Signature/)
})

/** The times StepMania's #OFFSET and #BPMS state, beats accumulated through the tempi (v3's `_stepmania_points`). */
function readStepmania(text) {
  const offset = Number(/#OFFSET:([^;]+);/.exec(text)[1])
  const pairs = /#BPMS:([^;]+);/
    .exec(text)[1]
    .split(',')
    .map((pair) => pair.trim().split('=').map(Number))
  let time = -offset * 1000
  return pairs.map(([beat, bpm], i) => {
    if (i) time += (beat - pairs[i - 1][0]) * (60000 / pairs[i - 1][1])
    return { time, beat, bpm }
  })
}

test('StepMania: negated offset in seconds, beat 0 at the first line, later beats accumulated', () => {
  const text = stepmaniaTimingText(lines)
  assert.equal(
    text,
    '// Generated by the Overtone site: timing only, no notes\n#OFFSET:-1.234567;\n#BPMS:0.000000=150.000000\n,75.378250=140.000000\n,135.378250=140.000000;\n',
  )
  const back = readStepmania(text)
  back.forEach((point, i) => assert.ok(Math.abs(point.time - lines[i].timeMs) < 0.001, `line ${i}`))
  // A first line before the audio starts is a positive offset.
  assert.match(stepmaniaTimingText([{ timeMs: -35.3, beatMs: 500, meter: 4 }], { offsetDecimals: 1 }), /#OFFSET:0.0353;/)
  assert.match(stepmaniaTimingText([{ timeMs: 0, beatMs: 500, meter: 4 }]), /#OFFSET:0.000000;/)
})

test("StepMania's 1/48-beat rows: the shift is measured, and zero on whole beats", () => {
  const shift = stepmaniaRowShift(lines)
  // 75.37825 beats lands on row 3618 (75.375): 0.00325 beats at 400 ms.
  assert.ok(Math.abs(shift.worstMs - 1.3) < 1e-6, String(shift.worstMs))
  assert.equal(shift.moved, 2)
  const onGrid = [
    { timeMs: 100, beatMs: 500, meter: 4 },
    { timeMs: 100 + 32 * 500, beatMs: 400, meter: 4 },
  ]
  assert.deepEqual(stepmaniaRowShift(onGrid), { worstMs: 0, moved: 0 })
})

test('.sm loses the meter and says so; .ssc writes #TIMESIGNATURES where the bar changes', () => {
  const common = { title: 'T', artist: 'A', creator: 'C', audioName: 'a#b;c.ogg', lines, offsetDecimals: 3 }
  const sm = stepmaniaFile({ ...common, kind: 'sm' })
  assert.equal(sm.report.meterLost, true)
  assert.doesNotMatch(sm.text, /#VERSION|#TIMESIGNATURES/)
  assert.match(sm.text, /^#MUSIC:abc.ogg;$/m)
  assert.doesNotMatch(sm.text, /#NOTES/)
  const ssc = stepmaniaFile({ ...common, kind: 'ssc' })
  assert.match(ssc.text, /^#VERSION:0.83;$/m)
  assert.match(ssc.text, /#TIMESIGNATURES:0.000000=4=4\n,75.378250=3=4\n,135.378250=4=4;/)
  assert.equal(ssc.report.meterLost, false)
  // Same meter, a line on the running bar: no new signature; off the bar: one.
  const onBar = [
    { timeMs: 0, beatMs: 500, meter: 4 },
    { timeMs: 8 * 500, beatMs: 400, meter: 4 },
    { timeMs: 8 * 500 + 3 * 400, beatMs: 400, meter: 4 },
  ]
  assert.match(stepmaniaFile({ ...common, lines: onBar, kind: 'ssc' }).text, /#TIMESIGNATURES:0.000000=4=4\n,11.000000=4=4;/)
})

/** Where each B marker sits in time by the game's arithmetic: ticks at the BPM in force. */
function readChart(text) {
  const events = [...text.matchAll(/^ {2}(\d+) = (B|TS) (\d+)$/gm)].map((m) => ({ tick: Number(m[1]), kind: m[2], value: Number(m[3]) }))
  const tempos = events.filter((e) => e.kind === 'B')
  let time = 0
  return {
    events,
    tempos: tempos.map((e, i) => {
      if (i) time += ((e.tick - tempos[i - 1].tick) / CHART_RESOLUTION) * (60000 / (tempos[i - 1].value / 1000))
      return { ...e, time }
    }),
  }
}

test('Clone Hero: a lead-in bar from tick 0, every change on its time, TS where the bar changes', () => {
  const { text, report } = chartFile({ title: 'Say "hi"', artist: 'A', creator: 'C', audioName: 'song.ogg', lines })
  assert.match(text, /^\[Song\]\r\n\{\r\n {2}Name = "Say 'hi'"\r\n/)
  assert.match(text, /\r\n {2}Offset = 0\r\n {2}Resolution = 192\r\n/)
  assert.doesNotMatch(text, /ExpertSingle|\bN \d/)
  const { events, tempos } = readChart(text)
  assert.ok(events.every((e) => Number.isInteger(e.value) && e.value > 0))
  // The lead-in: 4 beats from tick 0 to the first line's first downbeat at least half a bar in (1234.567 ms).
  assert.equal(report.leadIn, true)
  assert.equal(tempos[0].tick, 0)
  assert.equal(tempos[1].tick, 4 * CHART_RESOLUTION)
  assert.ok(Math.abs(tempos[1].time - 1234.567) < 0.01)
  // Each line's marker within the tolerance of its time.
  for (const [i, line] of lines.entries()) assert.ok(Math.abs(tempos[i + 1].time - line.timeMs) <= 0.5, `line ${i}: ${tempos[i + 1].time}`)
  assert.equal(report.fitted, 1)
  assert.ok(report.worstMs <= 0.5)
  // 140 BPM 3/4, then 4/4: a TS at each of those two ticks, the first at 0.
  const ts = events.filter((e) => e.kind === 'TS')
  assert.deepEqual(ts.map((e) => [e.tick, e.value]), [[0, 4], [tempos[2].tick, 3], [tempos[3].tick, 4]])
  assert.equal(tempos[3].value, 140000)
})

test('Clone Hero: no lead-in when a downbeat is on 0; a line before the audio is drawn forward', () => {
  const zero = chartSyncTrack([{ timeMs: 2000, beatMs: 500, meter: 4 }])
  assert.equal(zero.report.leadIn, false)
  assert.deepEqual(zero.events, [{ tick: 0, kind: 'TS', value: 4 }, { tick: 0, kind: 'B', value: 120000 }])
  const early = chartSyncTrack([{ timeMs: -100, beatMs: 500, meter: 4 }])
  // Downbeats at 1900, 3900...: the first at least half a bar (1000 ms) in is 1900.
  const lead = early.events.find((e) => e.kind === 'B' && e.tick === 0).value
  assert.ok(Math.abs((4 * 60000 * 1000) / lead - 1900) < 0.05)
  assert.equal(early.events.at(-1).value, 120000)
})

